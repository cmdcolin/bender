const pct = (v: number) => `${v > 0 ? '+' : ''}${(v * 100).toFixed(1)}%`

// One channel strip and the loop it records onto. The four are the same circuit,
// so they are written once and numbered.
function track(k: Track): SliderDef[] {
  return [
    {
      key: `four${k}In` as const,
      label: 'Input',
      min: 0,
      max: 3,
      step: 1,
      unit: '',
      choices: ['tape', 'board', 'mic', 'aux'],
      help: `The source of channel ${k}. Tape is loop ${k}’s playback, so recording puts it back on itself through the strip; board is the whole board’s output, a block behind; mic is the microphone; aux is the desk’s aux return, which with this channel’s aux send up is a mixer with nothing plugged into it.`,
    },
    {
      key: `four${k}Trim` as const,
      label: 'Trim',
      min: -20,
      max: 40,
      step: 0.5,
      unit: 'dB',
      reads: v => (v <= -20 ? 'off' : `${v > 0 ? '+' : ''}${v.toFixed(1)} dB`),
      help: 'The preamp. An op-amp with rails at twice the board’s full scale, so past about +20 dB a loud input squares off before the EQ sees it.',
    },
    {
      key: `four${k}Low` as const,
      label: 'Low',
      min: -15,
      max: 15,
      step: 0.5,
      unit: 'dB',
      split: { at: 0 },
      help: 'A shelf at 100 Hz.',
    },
    {
      key: `four${k}MidHz` as const,
      label: 'Mid freq',
      ...(k === 1 ? { lane: 'track 1 mid' } : {}),
      min: 250,
      max: 5000,
      step: 1,
      unit: 'Hz',
      curve: 'log',
      help: 'Where the sweepable mid sits, 250 Hz to 5 kHz. In a loop through the aux, this is the knob that tunes the squeal.',
    },
    {
      key: `four${k}Mid` as const,
      label: 'Mid',
      min: -15,
      max: 15,
      step: 0.5,
      unit: 'dB',
      split: { at: 0 },
      help: 'Boost or cut at Mid freq. Boosted in a feedback loop, the loop has the most gain there and screams at that pitch.',
    },
    {
      key: `four${k}High` as const,
      label: 'High',
      min: -15,
      max: 15,
      step: 0.5,
      unit: 'dB',
      split: { at: 0 },
      help: 'A shelf at 10 kHz.',
    },
    {
      key: `four${k}Send` as const,
      label: 'Aux send',
      min: 0,
      max: 1,
      step: 0.01,
      unit: '',
      help: 'How much of the channel, after its fader, goes to the aux bus. The aux bus comes back on any channel whose Input is aux.',
    },
    {
      key: `four${k}Pan` as const,
      label: 'Pan',
      min: -1,
      max: 1,
      step: 0.01,
      unit: '',
      split: { at: 0 },
      help: 'Where the channel and the loop’s cue sit across the stereo bus.',
    },
    {
      key: `four${k}Fader` as const,
      label: 'Fader',
      min: 0,
      max: 1,
      step: 0.01,
      unit: '',
      help: 'The channel to the stereo bus and the aux send. Down at stock: with Input on the board, the channel going back onto the board is a loop a block long, and it howls.',
    },
    {
      key: `four${k}Rec` as const,
      label: 'Record',
      min: 0,
      max: 1,
      step: 0.01,
      unit: '',
      help: `How much of the channel, after its EQ, the record head lays onto loop ${k}. The first time it comes up it threads a blank loop as long as Length.`,
    },
    {
      key: `four${k}Erase` as const,
      label: 'Erase',
      min: 0,
      max: 1,
      step: 0.01,
      unit: '',
      help: 'How much of what is already on the loop the erase head takes off while recording. At zero every pass piles onto the last until the oxide saturates; in between each pass is quieter and darker than the one before, because recording over tape takes its top end off first.',
    },
    {
      key: `four${k}Cue` as const,
      label: 'Cue',
      min: 0,
      max: 1,
      step: 0.01,
      unit: '',
      help: `Loop ${k}’s playback straight to the stereo bus, as the tape cue on a four-track does, whatever the channel’s input is set to.`,
    },
    {
      key: `four${k}Len` as const,
      label: 'Length',
      min: 0.5,
      max: MAX_LOOP_S,
      step: 0.05,
      unit: 's',
      help: `How long loop ${k} is, at 1⅞: at 3¾ it comes round twice as fast. Cut shorter while it runs, the splice moves and what was past it waits on the spool; cut longer than the tape threaded, and the record head threads more. Four loops of no common length drift against each other and never line up the same way twice.`,
    },
  ]
}

